#!/usr/bin/env node
/**
 * One-shot Comments GitHub App setup (manifest flow).
 *
 * Creates a GitHub App that:
 *  - identifies visitors (OAuth user-to-server)
 *  - writes Issues on priority.me via installation token
 *
 * Usage:
 *   node scripts/setup-comments-github.mjs
 *
 * Opens a browser → you approve → credentials land in
 * `.env.comments.local` + merged into `.env` (both gitignored).
 */
import http from 'node:http'
import { writeFileSync, readFileSync, existsSync } from 'node:fs'
import { randomBytes } from 'node:crypto'
import { execSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const __dirname = dirname(fileURLToPath(import.meta.url))
const root = join(__dirname, '..')
const PORT = 9877
const REDIRECT = `http://127.0.0.1:${PORT}/callback`
const SITE = 'https://razet.me'
const REPO = 'priority3/priority.me'
const APP_NAME = 'priority-me-comments'

const state = randomBytes(16).toString('hex')
const sessionSecret = randomBytes(32).toString('hex')

const manifest = {
  name: APP_NAME,
  url: SITE,
  redirect_url: REDIRECT,
  callback_urls: [
    `${SITE}/api/comments/auth/callback`,
    'https://priority-me.netlify.app/api/comments/auth/callback',
    'http://127.0.0.1:4321/api/comments/auth/callback',
    'http://localhost:4321/api/comments/auth/callback',
  ],
  hook_attributes: {
    url: `${SITE}/api/comments/github/webhook-unused`,
    active: false,
  },
  public: false,
  default_permissions: {
    issues: 'write',
    metadata: 'read',
  },
  // Request user identity for visitor login (GitHub App user-to-server OAuth).
  default_events: [],
}

function openBrowser(url) {
  const platform = process.platform
  try {
    if (platform === 'darwin') execSync(`open "${url}"`)
    else if (platform === 'win32') execSync(`start "" "${url}"`)
    else execSync(`xdg-open "${url}"`)
  } catch {
    console.log('\nOpen this URL manually:\n', url)
  }
}

function writeEnv({
  appId,
  clientId,
  clientSecret,
  pem,
  slug,
}) {
  // Single-line PEM for Netlify-friendly env
  const pemOneLine = pem.replace(/\n/g, '\\n')

  const body = `# Generated by scripts/setup-comments-github.mjs — DO NOT COMMIT
# Blog / Leetcode comments (GitHub App)

COMMENTS_GITHUB_APP_ID=${appId}
COMMENTS_GITHUB_CLIENT_ID=${clientId}
COMMENTS_GITHUB_CLIENT_SECRET=${clientSecret}
COMMENTS_GITHUB_PRIVATE_KEY="${pemOneLine}"
COMMENTS_SESSION_SECRET=${sessionSecret}
# Optional override instead of App installation token:
# COMMENTS_GITHUB_TOKEN=
`

  const out = join(root, '.env.comments.local')
  writeFileSync(out, body, 'utf8')

  const envPath = join(root, '.env')
  let existing = existsSync(envPath) ? readFileSync(envPath, 'utf8') : ''
  existing = existing.replace(
    /\n?# --- Comments \(auto\).*?(?=\n# ---|\n*$)/s,
    '\n',
  )
  const block = `
# --- Comments (auto) ---
COMMENTS_GITHUB_APP_ID=${appId}
COMMENTS_GITHUB_CLIENT_ID=${clientId}
COMMENTS_GITHUB_CLIENT_SECRET=${clientSecret}
COMMENTS_GITHUB_PRIVATE_KEY="${pemOneLine}"
COMMENTS_SESSION_SECRET=${sessionSecret}
`
  writeFileSync(envPath, `${existing.trim()}\n${block}\n`, 'utf8')
  return out
}

async function convertManifest(code) {
  const res = await fetch(
    `https://api.github.com/app-manifests/${code}/conversions`,
    {
      method: 'POST',
      headers: {
        Accept: 'application/vnd.github+json',
        'X-GitHub-Api-Version': '2022-11-28',
        'User-Agent': 'priority-me-comments-setup',
      },
    },
  )
  if (!res.ok) {
    const text = await res.text()
    throw new Error(`Manifest conversion failed (${res.status}): ${text}`)
  }
  return res.json()
}

const server = http.createServer(async (req, res) => {
  const url = new URL(req.url || '/', `http://127.0.0.1:${PORT}`)

  if (url.pathname === '/') {
    res.writeHead(200, { 'Content-Type': 'text/html; charset=utf-8' })
    res.end(`<!doctype html>
<html><body style="font-family:system-ui;padding:2rem;max-width:42rem;line-height:1.5">
  <h1>Create Comments GitHub App</h1>
  <p>This app lets visitors sign in with GitHub and stores comments as Issues
  on <code>${REPO}</code> (label <code>blog-comment</code>).</p>
  <p>Permissions: <strong>Issues (write)</strong>, <strong>Metadata (read)</strong>.</p>
  <form action="https://github.com/settings/apps/new?state=${state}" method="post">
    <input type="hidden" name="manifest" value='${JSON.stringify(manifest).replace(/'/g, '&#39;')}' />
    <button type="submit" style="font-size:1.1rem;padding:.65rem 1.25rem;cursor:pointer;border-radius:8px;border:1px solid #ccc;background:#f6f8fa">
      Create GitHub App on GitHub
    </button>
  </form>
</body></html>`)
    return
  }

  if (url.pathname === '/callback') {
    const code = url.searchParams.get('code')
    const returnedState = url.searchParams.get('state')
    if (!code) {
      res.writeHead(400, { 'Content-Type': 'text/plain' })
      res.end('Missing code')
      return
    }
    if (returnedState && returnedState !== state) {
      res.writeHead(400, { 'Content-Type': 'text/plain' })
      res.end('Invalid state')
      return
    }

    try {
      const app = await convertManifest(code)
      const appId = String(app.id)
      const clientId = app.client_id
      const clientSecret = app.client_secret
      const pem = app.pem
      const slug = app.slug

      if (!clientId || !clientSecret || !pem) {
        throw new Error('Manifest conversion missing client_id/secret/pem')
      }

      const out = writeEnv({ appId, clientId, clientSecret, pem, slug })
      const installUrl = `https://github.com/apps/${slug}/installations/new/permissions?target_id=75966543`

      // Simpler install URL
      const installUrlSimple = `https://github.com/apps/${slug}/installations/new`

      console.log('\n✅ Comments GitHub App created:', slug)
      console.log('   App ID:', appId)
      console.log('   Client ID:', clientId)
      console.log('   Credentials →', out, '+ .env')
      console.log('\n👉 Install the App on the repo (Issues write):')
      console.log('  ', installUrlSimple)
      console.log('   Only select repositories → priority.me\n')

      res.writeHead(200, { 'Content-Type': 'text/html; charset=utf-8' })
      res.end(`<!doctype html>
<html><body style="font-family:system-ui;padding:2rem;max-width:42rem;line-height:1.5">
  <h1>✅ App created</h1>
  <p><strong>Slug:</strong> ${slug}</p>
  <p><strong>App ID:</strong> ${appId}</p>
  <p>Credentials saved to <code>.env.comments.local</code> and <code>.env</code>.</p>
  <p style="margin-top:1.5rem">
    <a href="${installUrlSimple}" style="font-size:1.15rem;font-weight:600">
      Install App on priority.me →
    </a>
  </p>
  <p>Choose <em>Only select repositories</em> → <code>priority.me</code>, then confirm.</p>
  <p>You can close this tab after installing. Check the terminal for Netlify steps.</p>
</body></html>`)

      openBrowser(installUrlSimple)

      setTimeout(() => {
        server.close()
        printHelp({ appId, clientId, clientSecret, pem, slug, sessionSecret })
        process.exit(0)
      }, 800)
    } catch (err) {
      console.error(err)
      res.writeHead(500, { 'Content-Type': 'text/plain' })
      res.end(String(err))
    }
    return
  }

  res.writeHead(404)
  res.end('Not found')
})

function printHelp({ appId, clientId, clientSecret, pem, slug, sessionSecret }) {
  const pemOneLine = pem.replace(/\n/g, '\\n')
  console.log(`
════════════════════════════════════════════════════════
Next steps
════════════════════════════════════════════════════════

1) Finish installing the App on ${REPO}
   https://github.com/apps/${slug}/installations/new

2) Netlify → Site configuration → Environment variables
   (or: pnpm exec netlify env:set … after netlify login + link)

COMMENTS_GITHUB_APP_ID=${appId}
COMMENTS_GITHUB_CLIENT_ID=${clientId}
COMMENTS_GITHUB_CLIENT_SECRET=${clientSecret}
COMMENTS_GITHUB_PRIVATE_KEY=${pemOneLine}
COMMENTS_SESSION_SECRET=${sessionSecret}

3) Redeploy the site.

4) Local: credentials already in .env — run pnpm dev and open a post.

Optional helper:
  node scripts/push-comments-env-to-netlify.mjs
`)
}

server.listen(PORT, '127.0.0.1', () => {
  const url = `http://127.0.0.1:${PORT}/`
  console.log(`
Comments GitHub App setup
─────────────────────────
1. Browser opens: ${url}
2. Click "Create GitHub App on GitHub" and approve
3. Install on ${REPO}
4. Env vars printed for Netlify

Waiting on ${REDIRECT} …
`)
  openBrowser(url)
})
